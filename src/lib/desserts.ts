const makeIngredient = ([id, quantity]: [string, number]): Ingredient => {
  const catalog = ingredientById.get(id);
  const shared = sharedIngredients[id];
  if (!catalog && !shared)
    throw new Error(`Ingrediente dolce sconosciuto: ${id}`);
  return catalog
    ? {
        id,
        name: catalog.name,
        unit: catalog.unit,
        quantity,
        category: catalog.category,
        allergens: catalog.allergens,
      }
    : { ...shared, quantity };
};

