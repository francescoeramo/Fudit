export const dessertRecipes: Recipe[] = specs.map((spec) => {
  const ingredients = spec.ingredients.map(makeIngredient);
  const allergenSet = new Set(
    ingredients.flatMap((item) => item.allergens ?? []),
  );
  const tags: Recipe["tags"] = ["dolci", "vegetariani"];
  if (!allergenSet.has("glutine")) tags.push("senza glutine");
  if (!allergenSet.has("latte")) tags.push("senza lattosio");
  if (spec.lowFodmap) tags.push("low FODMAP");
  return {
    id: `dolce-${spec.id}`,
    title: spec.title,
    time: spec.minutes,
    difficulty: spec.minutes > 55 ? "Media" : "Facile",
    ingredients,
    steps: buildDessertSteps({
      title: spec.title,
      kind: spec.kind,
      ingredients,
    }),
    nutrition: nutrition(320, 6, 42, 14),
    tags,
    allergens: [...allergenSet],
    baseServings: 8,
    course: "Dolce",
    origin: "seed",
  };
});
