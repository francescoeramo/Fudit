export const createSavoryRecipes = (catalog: PriceItem[]): Recipe[] =>
  savoryRecipeSpecs.map((spec) => {
    const ingredients = spec.ingredients.map(([id, quantity]) => {
      const item = catalog.find((candidate) => candidate.id === id);
      if (!item)
        throw new Error(`Ingrediente ricetta salata sconosciuto: ${id}`);
      return {
        id: item.id,
        name: item.name,
        unit: item.unit,
        quantity,
        category: item.category,
        allergens: [...item.allergens],
      };
    });
    const ids = new Set(ingredients.map((ingredient) => ingredient.id));
    const allergens = [
      ...new Set(
        ingredients.flatMap((ingredient) => ingredient.allergens ?? []),
      ),
    ];
    const tags = new Set<Recipe["tags"][number]>(spec.tags ?? []);
    if (spec.asian) tags.add("asiatici");
    if (![...ids].some((id) => meatIds.has(id))) tags.add("vegetariani");
    if (![...ids].some((id) => animalIds.has(id))) tags.add("vegani");
    if (!allergens.includes("glutine")) tags.add("senza glutine");
    if (!allergens.includes("latte")) tags.add("senza lattosio");
    const draft = {
      title: spec.title,
      ingredients,
      steps: baseSteps(spec.method),
      time: spec.minutes,
    };
    return {
      id: `salato-${spec.id}`,
      title: spec.title,
      time: spec.minutes,
      difficulty: spec.minutes >= 50 ? "Media" : "Facile",
      ingredients,
      steps: buildSavorySteps(draft),
      nutrition: nutrition(510, 25, 58, 18),
      tags: [...tags],
      allergens,
      baseServings: 2,
      course: spec.course,
      origin: "seed",
    };
  });
