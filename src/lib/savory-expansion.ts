const storesFor = (base: number) => ({
  Lidl: +(base * 0.92).toFixed(2),
  Eurospin: +(base * 0.88).toFixed(2),
  Esselunga: +(base * 1.08).toFixed(2),
  Coop: +(base * 1.1).toFixed(2),
  Conad: +(base * 1.04).toFixed(2),
  Despar: +(base * 1.06).toFixed(2),
  Penny: +(base * 0.9).toFixed(2),
  MD: +(base * 0.89).toFixed(2),
  Altro: base,
});

